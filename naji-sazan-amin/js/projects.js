const wrap = (inner) =>
  `<svg viewBox="0 0 800 600" preserveAspectRatio="xMidYMid slice" fill="none"
        stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
     <g opacity="0.9">${inner}</g>
   </svg>`;

/* soft ground + horizon, shared by most scenes */
const ground = (y = 512) =>
  `<line x1="40" y1="${y}" x2="760" y2="${y}" stroke-width="2" opacity="0.35"/>
   <line x1="40" y1="${y + 26}" x2="760" y2="${y + 26}" stroke-width="1.5" opacity="0.18"/>`;

