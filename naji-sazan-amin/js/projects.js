window.NSA_drawing = function (p) {
  switch (p.type) {
    case 'tower':          return wrap(drawTower());
    case 'complex':        return wrap(drawComplex());
    case 'cultural':       return wrap(drawCultural());
    case 'healthcare':     return wrap(drawHealthcare());
    case 'office':         return wrap(drawOffice());
    case 'villa':          return wrap(drawVilla());
    case 'restoration':    return wrap(drawRestoration());
    case 'infrastructure': return wrap(drawBridge());
    default:               return wrap(drawTower());
  }
};

/* ---- Residential tower ---- */
function drawTower() {
  const x = 300, w = 200, top = 92, base = 512;
  let floors = '';
  const n = 22, fh = (base - top) / n;
  for (let i = 1; i < n; i++) floors += `<line x1="${x}" y1="${top + i * fh}" x2="${x + w}" y2="${top + i * fh}" stroke-width="1.2" opacity="0.4"/>`;
  let bays = '';
  for (let j = 1; j < 4; j++) bays += `<line x1="${x + j * (w / 4)}" y1="${top + 18}" x2="${x + j * (w / 4)}" y2="${base}" stroke-width="1.2" opacity="0.28"/>`;
  return `
    ${skyline(512)}
    <rect x="${x}" y="${top}" width="${w}" height="${base - top}" rx="4" opacity="0.06" fill="currentColor" stroke="none"/>
    <path d="M${x - 16},${top} L${x + w + 16},${top}"/>
    <path d="M${x},${top} L${x},${base} M${x + w},${top} L${x + w},${base}"/>
    <path d="M${x},${base} L${x + w},${base}"/>
    ${floors}${bays}
    <path d="M${x + 44},${top} L${x + 44},${top - 34} L${x + w - 44},${top - 34} L${x + w - 44},${top}" opacity="0.5"/>
    <rect x="${x - 40}" y="${base - 34}" width="${w + 80}" height="34" rx="3" opacity="0.5"/>
    ${ground(546)}`;
}

/* ---- Commercial complex ---- */
function drawComplex() {
  const blocks = [
    { x: 130, y: 372, w: 168, h: 140 },
    { x: 306, y: 286, w: 152, h: 226 },
    { x: 466, y: 322, w: 136, h: 190 },
    { x: 610, y: 396, w: 118, h: 116 },
  ];
  let out = skyline(512);
  blocks.forEach((b) => {
    out += `<rect x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" rx="3" opacity="0.06" fill="currentColor" stroke="none"/>`;
    out += `<rect x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" rx="3" stroke-width="2"/>`;
    out += `<line x1="${b.x}" y1="${b.y + 26}" x2="${b.x + b.w}" y2="${b.y + 26}" stroke-width="1.4" opacity="0.45"/>`;
    const cols = Math.max(2, Math.round(b.w / 34));
    for (let c = 1; c < cols; c++) {
      const cx = b.x + (c * b.w) / cols;
      out += `<line x1="${cx}" y1="${b.y + 26}" x2="${cx}" y2="${b.y + b.h}" stroke-width="1" opacity="0.25"/>`;
    }
    const rows = Math.max(2, Math.round((b.h - 26) / 34));
    for (let r = 1; r < rows; r++) {
      const cy = b.y + 26 + (r * (b.h - 26)) / rows;
      out += `<line x1="${b.x}" y1="${cy}" x2="${b.x + b.w}" y2="${cy}" stroke-width="1" opacity="0.25"/>`;
    }
  });
  return out + `<rect x="96" y="512" width="656" height="30" rx="3" opacity="0.5"/>` + ground(542);
}

