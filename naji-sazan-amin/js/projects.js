/* ================================================================
   Rendering
   ================================================================ */
(function () {
  const revealAll = (root) => {
    if (!('IntersectionObserver' in window)) {
      root.querySelectorAll('.reveal').forEach((el) => el.classList.add('is-visible'));
      return;
    }
    const io = new IntersectionObserver((entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) { e.target.classList.add('is-visible'); io.unobserve(e.target); }
      });
    }, { threshold: 0.1 });
    root.querySelectorAll('.reveal').forEach((el) => io.observe(el));
  };

  const mediaHTML = (p) => {
    if (p.image) {
      return '<img src="' + p.image + '" alt="' + p.title +
        '" loading="lazy" decoding="async" width="800" height="600">';
    }
    return window.NSA_drawing(p);
  };

  const card = (p, i, featured) => {
    const el = document.createElement('article');
    el.className = 'project spotlight-card reveal';
    el.dataset.project = p.id;
    el.dataset.cat = p.categorySlug;
    if (i % 3) el.setAttribute('data-delay', String(i % 3));
    el.innerHTML =
      '<div class="project__media">' + mediaHTML(p) + '</div>' +
      '<div class="project__body">' +
        '<span class="project__cat">' + p.category + '</span>' +
        '<h3 class="project__title">' + p.title + '</h3>' +
        '<p class="project__summary">' + p.summary + '</p>' +
        '<div class="project__foot">' +
          '<span>' + p.location + '</span>' +
          '<span>' + p.year + '</span>' +
        '</div>' +
      '</div>';
    return el;
  };

  const featuredGrid = document.getElementById('featuredGrid');
  if (featuredGrid && window.NSA_PROJECTS) {
    ['parsa-tower', 'saft-defense-museum', 'atlas-complex', 'al-zahra-hospital'].forEach((id, i) => {
      const p = window.NSA_PROJECTS.find((x) => x.id === id);
      if (p) featuredGrid.appendChild(card(p, i, true));
    });
    revealAll(featuredGrid);
    window.initSpotlights && window.initSpotlights();
  }

  const grid = document.getElementById('projectGrid');
  if (grid && window.NSA_PROJECTS) {
    const counts = { all: window.NSA_PROJECTS.length };
    window.NSA_PROJECTS.forEach((p) => { counts[p.categorySlug] = (counts[p.categorySlug] || 0) + 1; });
    Object.keys(counts).forEach((k) => {
      const el = document.getElementById('cnt-' + k);
      if (el) el.textContent = '(' + counts[k] + ')';
    });
    window.NSA_PROJECTS.forEach((p, i) => grid.appendChild(card(p, i, false)));
    revealAll(grid);
    window.initSpotlights && window.initSpotlights();
  }
})();
